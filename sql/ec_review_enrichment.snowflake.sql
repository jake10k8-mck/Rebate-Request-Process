WITH REQUESTED AS (
    SELECT value:line_key::INTEGER AS LINE_KEY,
           TRY_TO_NUMBER(value:account_number::VARCHAR) AS ACCOUNT_NUMBER,
           TRY_TO_NUMBER(value:item::VARCHAR) AS ITEM_E1_NUM
    FROM TABLE(FLATTEN(INPUT => PARSE_JSON(%s)))
),
CUSTOMER_ROWS AS (
    SELECT DISTINCT CUST_E1_NUM, PRCA_NUM
    FROM PRD_PL_MMS_EDW_DB.EDWRPT.V_DIM_CUST_CURR
    WHERE SYS_PLTFRM = 'E1' AND CUST_TYPE_CD IN ('B', 'S', 'X')
      AND CUST_E1_NUM IN (SELECT ACCOUNT_NUMBER FROM REQUESTED)
),
CUSTOMERS AS (
    SELECT CUST_E1_NUM, COUNT(*) AS CUSTOMER_MATCHES,
           CASE WHEN COUNT(*) = 1 THEN MIN(PRCA_NUM) END AS PRCA_NUM
    FROM CUSTOMER_ROWS GROUP BY CUST_E1_NUM
),
ITEM_ROWS AS (
    SELECT DISTINCT ITEM_E1_NUM, ITEM_DSC, PRMRY_UOM, SELL_UOM, BUY_UOM,
           MAC_COST_AMT, EC_VIP_COST_AMT / NULLIF(SELL_TO_BUY_DIVISOR, 0) AS EC_ACQ_COST
    FROM PRD_PL_MMS_EDW_DB.EDWRPT.V_DIM_ITEM_E1_CURR
    WHERE PRVT_BRND_FLG = 'Y' AND STOCK_TYPE_CD <> 'O'
      AND ITEM_E1_NUM IN (SELECT ITEM_E1_NUM FROM REQUESTED)
),
ITEMS AS (
    SELECT ITEM_E1_NUM, COUNT(*) AS ITEM_MATCHES,
           CASE WHEN COUNT(*) = 1 THEN MIN(ITEM_DSC) END AS ITEM_DSC,
           CASE WHEN COUNT(*) = 1 THEN MIN(SELL_UOM) END AS SELL_UOM,
           CASE WHEN COUNT(*) = 1 THEN MIN(PRMRY_UOM) END AS PRMRY_UOM,
           CASE WHEN COUNT(*) = 1 THEN MIN(BUY_UOM) END AS BUY_UOM,
           CASE WHEN COUNT(*) = 1 THEN MIN(MAC_COST_AMT) END AS MAC_COST_AMT,
           CASE WHEN COUNT(*) = 1 THEN MIN(EC_ACQ_COST) END AS EC_ACQ_COST
    FROM ITEM_ROWS GROUP BY ITEM_E1_NUM
),
PEX_ROWS AS (
    SELECT DISTINCT PRCA_NUM, BUS_PLTFRM, PRICING_DECISION_MAKER_REP_NAME, HCN_CUST_SIZE
    FROM PRD_SBX_MMS_DB.PRC.PEX_PRCA_VIEW
    WHERE PRCA_NUM IN (SELECT PRCA_NUM FROM CUSTOMERS)
),
PEX AS (
    SELECT PRCA_NUM, COUNT(*) AS PEX_MATCHES,
           CASE WHEN COUNT(*) = 1 THEN MIN(BUS_PLTFRM) END AS BUS_PLTFRM,
           CASE WHEN COUNT(*) = 1 THEN MIN(PRICING_DECISION_MAKER_REP_NAME) END AS REP_NAME,
           CASE WHEN COUNT(*) = 1 THEN MIN(HCN_CUST_SIZE) END AS HCN_CUST_SIZE
    FROM PEX_ROWS GROUP BY PRCA_NUM
),
TAPESTRY_ROWS AS (
    SELECT DISTINCT ITEM_E1_NUM, GROUPED_LVL2,
           TIER_1, TIER_2, TIER_3, TIER_4, TIER_5,
           TIER_6, TIER_7, TIER_8, TIER_9, TIER_10
    FROM PRD_SBX_MMS_DB.VALUEPLUS.MCKB_COST_TAPESTRY
    WHERE ITEM_E1_NUM IN (SELECT ITEM_E1_NUM FROM REQUESTED)
),
TAPESTRY AS (
    SELECT ITEM_E1_NUM, COUNT(*) AS TAPESTRY_MATCHES,
           CASE WHEN COUNT(*) = 1 THEN MIN(GROUPED_LVL2) END AS GROUPED_LVL2,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_1) END AS TIER_1,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_2) END AS TIER_2,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_3) END AS TIER_3,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_4) END AS TIER_4,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_5) END AS TIER_5,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_6) END AS TIER_6,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_7) END AS TIER_7,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_8) END AS TIER_8,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_9) END AS TIER_9,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_10) END AS TIER_10
    FROM TAPESTRY_ROWS GROUP BY ITEM_E1_NUM
),
TIER_COSTS AS (
    SELECT ITEM_E1_NUM, REGEXP_SUBSTR(TIER_NAME, '[0-9]+')::INTEGER AS TIER_NUM, TIER_COST
    FROM TAPESTRY UNPIVOT INCLUDE NULLS (
        TIER_COST FOR TIER_NAME IN (TIER_1, TIER_2, TIER_3, TIER_4, TIER_5,
                                   TIER_6, TIER_7, TIER_8, TIER_9, TIER_10)
    )
),
ATTACHMENT_ROWS AS (
    SELECT DISTINCT PRCA_NUM, GROUPED_LVL2, ATTACHED_TIER
    FROM PRD_SBX_MMS_DB.PRC.TAP_CUST_ATTACHED_TIERS
    WHERE PRCA_NUM IN (SELECT PRCA_NUM FROM CUSTOMERS)
),
ATTACHMENTS AS (
    SELECT PRCA_NUM, GROUPED_LVL2, COUNT(*) AS ATTACHMENT_MATCHES,
           CASE WHEN COUNT(*) = 1 THEN MIN(TRY_TO_NUMBER(REGEXP_SUBSTR(ATTACHED_TIER, '[0-9]+'))) END AS CURRENT_TIER
    FROM ATTACHMENT_ROWS GROUP BY PRCA_NUM, GROUPED_LVL2
),
IPC_TOTAL AS (
    SELECT BID_OR_PRCA, ITEM_E1_NUM, COUNT(*) AS IPC_ALL_ROWS
    FROM PRD_SBX_MMS_DB.MRGN.HAH_IPC
    WHERE BID_OR_PRCA IN (SELECT PRCA_NUM FROM CUSTOMERS)
      AND ITEM_E1_NUM IN (SELECT ITEM_E1_NUM FROM REQUESTED)
    GROUP BY BID_OR_PRCA, ITEM_E1_NUM
),
IPC AS (
    SELECT BID_OR_PRCA, ITEM_E1_NUM, UPPER(TRIM(SELL_UOM)) AS SELL_UOM,
           COUNT(*) AS IPC_MATCHED_ROWS,
           CASE WHEN COUNT(QTY_3_MTH) = COUNT(*) THEN SUM(QTY_3_MTH) END AS QTY_3_MTH,
           CASE WHEN COUNT(SLS_3_MTH) = COUNT(*) THEN SUM(SLS_3_MTH) END AS SLS_3_MTH,
           COUNT_IF(QTY_3_MTH < 0 OR SLS_3_MTH < 0) AS NEGATIVE_ACTIVITY_ROWS,
           COUNT_IF(PR_UOM IS NULL OR UPPER(TRIM(PR_UOM)) <> UPPER(TRIM(SELL_UOM))) AS PRICE_UOM_MISMATCH_ROWS,
           COUNT(DISTINCT UNIT_PRICE) AS DISTINCT_CURRENT_PRICES,
           MIN(UNIT_PRICE) AS CURRENT_PRICE_MIN, MAX(UNIT_PRICE) AS CURRENT_PRICE_MAX,
           MIN(PRICE_DATE) AS IPC_PRICE_DATE_MIN, MAX(PRICE_DATE) AS IPC_PRICE_DATE_MAX
    FROM PRD_SBX_MMS_DB.MRGN.HAH_IPC
    WHERE BID_OR_PRCA IN (SELECT PRCA_NUM FROM CUSTOMERS)
      AND ITEM_E1_NUM IN (SELECT ITEM_E1_NUM FROM REQUESTED)
    GROUP BY BID_OR_PRCA, ITEM_E1_NUM, UPPER(TRIM(SELL_UOM))
),
TIERS AS (
    SELECT COLUMN1 AS TIER_NUM, COLUMN2 AS TIER_TARGET_MARGIN
    FROM VALUES (1, 0.25), (2, 0.23), (3, 0.21), (4, 0.18), (5, 0.16),
                (6, 0.14), (7, 0.12), (8, 0.09), (9, 0.07), (10, 0.05)
)
SELECT request.LINE_KEY, customer.PRCA_NUM, customer.CUSTOMER_MATCHES,
       item.ITEM_MATCHES, item.ITEM_DSC, item.SELL_UOM, item.PRMRY_UOM, item.BUY_UOM,
       item.MAC_COST_AMT, item.EC_ACQ_COST,
       pex.PEX_MATCHES, pex.BUS_PLTFRM, pex.REP_NAME, pex.HCN_CUST_SIZE,
       tapestry.TAPESTRY_MATCHES, tapestry.GROUPED_LVL2,
       attachment.ATTACHMENT_MATCHES, attachment.CURRENT_TIER,
       current_cost.TIER_COST AS CURRENT_TIER_COST,
    tiers.TIER_NUM, tiers.TIER_TARGET_MARGIN, candidate.TIER_COST,
    ROUND(candidate.TIER_COST / (1 - tiers.TIER_TARGET_MARGIN), 2) AS BENCHMARK_PRICE,
       ipc_total.IPC_ALL_ROWS, ipc.IPC_MATCHED_ROWS, ipc.QTY_3_MTH, ipc.SLS_3_MTH,
       ipc.NEGATIVE_ACTIVITY_ROWS, ipc.PRICE_UOM_MISMATCH_ROWS,
       ipc.DISTINCT_CURRENT_PRICES, ipc.CURRENT_PRICE_MIN, ipc.CURRENT_PRICE_MAX,
       ipc.IPC_PRICE_DATE_MIN, ipc.IPC_PRICE_DATE_MAX
FROM REQUESTED request CROSS JOIN TIERS tiers
LEFT JOIN CUSTOMERS customer ON customer.CUST_E1_NUM = request.ACCOUNT_NUMBER
LEFT JOIN ITEMS item ON item.ITEM_E1_NUM = request.ITEM_E1_NUM
LEFT JOIN PEX pex ON pex.PRCA_NUM = customer.PRCA_NUM
LEFT JOIN TAPESTRY tapestry ON tapestry.ITEM_E1_NUM = request.ITEM_E1_NUM
LEFT JOIN ATTACHMENTS attachment ON attachment.PRCA_NUM = customer.PRCA_NUM
    AND attachment.GROUPED_LVL2 = tapestry.GROUPED_LVL2
LEFT JOIN TIER_COSTS current_cost ON current_cost.ITEM_E1_NUM = request.ITEM_E1_NUM
    AND current_cost.TIER_NUM = attachment.CURRENT_TIER
LEFT JOIN TIER_COSTS candidate ON candidate.ITEM_E1_NUM = request.ITEM_E1_NUM
    AND candidate.TIER_NUM = tiers.TIER_NUM
LEFT JOIN IPC_TOTAL ipc_total ON ipc_total.BID_OR_PRCA = customer.PRCA_NUM
    AND ipc_total.ITEM_E1_NUM = request.ITEM_E1_NUM
LEFT JOIN IPC ipc ON ipc.BID_OR_PRCA = customer.PRCA_NUM
    AND ipc.ITEM_E1_NUM = request.ITEM_E1_NUM AND ipc.SELL_UOM = UPPER(TRIM(item.SELL_UOM))
ORDER BY request.LINE_KEY, tiers.TIER_NUM