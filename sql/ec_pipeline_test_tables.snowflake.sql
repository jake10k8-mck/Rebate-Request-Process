CREATE TRANSIENT TABLE IF NOT EXISTS PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_HEADER_PIPELINE_TEST
COMMENT = 'Isolated EC pipeline test input. September 24-30 2026 source snapshot; not approved pricing.'
AS
SELECT *
FROM PRD_SBX_MMS_DB.PRC.MCKB_REBATE_REQUEST_HEADER
WHERE TRY_TO_TIMESTAMP_NTZ(CREATED_DT) >= '2026-09-24'::TIMESTAMP_NTZ
  AND TRY_TO_TIMESTAMP_NTZ(CREATED_DT) < '2026-10-01'::TIMESTAMP_NTZ
  AND BUS_PLTFRM_DSC = 'Extended Care'
ORDER BY TRY_TO_TIMESTAMP_NTZ(CREATED_DT), ROW_ID
LIMIT 25;

CREATE TRANSIENT TABLE IF NOT EXISTS PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_LINES_PIPELINE_TEST
COMMENT = 'Requested lines for isolated EC pipeline test headers; not approved pricing.'
AS
SELECT lines.*
FROM PRD_SBX_MMS_DB.PRC.MCKB_REBATE_REQUEST_LINES lines
WHERE lines.ROW_ID IN (
    SELECT ROW_ID FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_HEADER_PIPELINE_TEST
);

SELECT 'EC_REBATE_REQUEST_HEADER_PIPELINE_TEST' AS TABLE_NAME, COUNT(*) AS ROW_COUNT
FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_HEADER_PIPELINE_TEST
UNION ALL
SELECT 'EC_REBATE_REQUEST_LINES_PIPELINE_TEST', COUNT(*)
FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_LINES_PIPELINE_TEST;

SELECT COUNT(*) AS ORPHAN_LINE_COUNT
FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_LINES_PIPELINE_TEST lines
WHERE NOT EXISTS (
    SELECT 1 FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_HEADER_PIPELINE_TEST headers
    WHERE headers.ROW_ID = lines.ROW_ID
);