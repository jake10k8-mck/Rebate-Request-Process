WITH CUSTOMERS AS (
    SELECT value::NUMBER AS PRCA_NUM FROM TABLE(FLATTEN(INPUT => PARSE_JSON(%s)))
),
IPC AS (
    SELECT BID_OR_PRCA AS PRCA_NUM, ITEM_E1_NUM, UPPER(TRIM(SELL_UOM)) AS IPC_SELL_UOM,
           COUNT(*) AS IPC_ROWS,
           CASE WHEN COUNT(QTY_3_MTH) = COUNT(*) THEN SUM(QTY_3_MTH) END AS QTY_3_MTH,
           CASE WHEN COUNT(SLS_3_MTH) = COUNT(*) THEN SUM(SLS_3_MTH) END AS SLS_3_MTH,
           COUNT_IF(QTY_3_MTH < 0 OR SLS_3_MTH < 0) AS NEGATIVE_ACTIVITY_ROWS
    FROM PRD_SBX_MMS_DB.MRGN.HAH_IPC
    WHERE BID_OR_PRCA IN (SELECT PRCA_NUM FROM CUSTOMERS)
    GROUP BY BID_OR_PRCA, ITEM_E1_NUM, UPPER(TRIM(SELL_UOM))
),
ITEM_ROWS AS (
    SELECT DISTINCT ITEM_E1_NUM, ITEM_DSC, PRMRY_UOM, SELL_UOM, BUY_UOM,
           SELL_TO_BUY_DIVISOR, PRMRY_TO_SELL_DIVISOR, PRMRY_TO_BUY_DIVISOR,
           PRVT_BRND_FLG
    FROM PRD_PL_MMS_EDW_DB.EDWRPT.V_DIM_ITEM_E1_CURR
    WHERE ITEM_E1_NUM IN (SELECT ITEM_E1_NUM FROM IPC)
),
ITEMS AS (
    SELECT ITEM_E1_NUM, COUNT(*) AS ITEM_MATCHES,
           CASE WHEN COUNT(*) = 1 THEN MIN(ITEM_DSC) END AS ITEM_DSC,
           CASE WHEN COUNT(*) = 1 THEN MIN(PRMRY_UOM) END AS PRMRY_UOM,
           CASE WHEN COUNT(*) = 1 THEN MIN(SELL_UOM) END AS REFERENCE_SELL_UOM,
           CASE WHEN COUNT(*) = 1 THEN MIN(BUY_UOM) END AS BUY_UOM,
           CASE WHEN COUNT(*) = 1 THEN MIN(SELL_TO_BUY_DIVISOR) END AS SELL_TO_BUY_DIVISOR,
           CASE WHEN COUNT(*) = 1 THEN MIN(PRMRY_TO_SELL_DIVISOR) END AS PRMRY_TO_SELL_DIVISOR,
           CASE WHEN COUNT(*) = 1 THEN MIN(PRMRY_TO_BUY_DIVISOR) END AS PRMRY_TO_BUY_DIVISOR,
           CASE WHEN COUNT(*) = 1 THEN MIN(PRVT_BRND_FLG) END AS PRVT_BRND_FLG
    FROM ITEM_ROWS GROUP BY ITEM_E1_NUM
),
CUSTOMER_DETAIL_ROWS AS (
    SELECT DISTINCT PRCA_NUM, CUST_E1_NUM, CUST_TYPE_CD, CUST_NAME
    FROM PRD_PL_MMS_EDW_DB.EDWRPT.V_DIM_CUST_CURR
    WHERE SYS_PLTFRM = 'E1'
      AND PRCA_NUM IN (SELECT PRCA_NUM FROM CUSTOMERS)
),
PENNY_ACTIVE_ROWS AS (
    SELECT DISTINCT TRY_TO_NUMBER(penny.ITEM_NUM) AS ITEM_E1_NUM,
           penny.PRODUCT_TYPE, penny.MAN_CONTRACT_ID,
           contract.MCK_CNTRCT_ID, contract.SHIP_TO_ELIG_RQRD_FLG
    FROM PRD_SBX_MMS_DB.PRC.MCKB_PENNY_CONTRACT_INFO penny
    LEFT JOIN PRD_PL_MMS_DATALAKE_DB.MMSDW.CONTRACT_HEADER contract
      ON UPPER(TRIM(contract.MAN_CNTRCT_ID)) = UPPER(TRIM(penny.MAN_CONTRACT_ID))
    WHERE CURRENT_DATE() BETWEEN penny.START_DT AND penny.END_DT
      AND TRY_TO_NUMBER(penny.ITEM_NUM) IN (SELECT ITEM_E1_NUM FROM IPC)
),
PENNY_CONTRACTS AS (
    SELECT ITEM_E1_NUM, COUNT(*) AS PENNY_CONTRACT_MATCH_COUNT,
           LISTAGG(DISTINCT PRODUCT_TYPE, ' | ') WITHIN GROUP (ORDER BY PRODUCT_TYPE) AS PENNY_PRODUCT_TYPES,
           LISTAGG(DISTINCT MAN_CONTRACT_ID, ' | ') WITHIN GROUP (ORDER BY MAN_CONTRACT_ID) AS PENNY_MAN_CONTRACT_IDS,
           LISTAGG(DISTINCT MCK_CNTRCT_ID::VARCHAR, ' | ') WITHIN GROUP (ORDER BY MCK_CNTRCT_ID::VARCHAR) AS PENNY_MCK_CONTRACT_IDS,
           LISTAGG(DISTINCT SHIP_TO_ELIG_RQRD_FLG, ' | ') WITHIN GROUP (ORDER BY SHIP_TO_ELIG_RQRD_FLG) AS PENNY_SHIP_TO_ELIG_FLAGS,
           COUNT(*) > 1 OR COUNT(DISTINCT MCK_CNTRCT_ID) > 1 AS PENNY_CONTRACT_AMBIGUOUS
    FROM PENNY_ACTIVE_ROWS
    GROUP BY ITEM_E1_NUM
),
PENNY_CUSTOMER_CHECKS AS (
    SELECT ipc.PRCA_NUM, ipc.ITEM_E1_NUM,
           penny.SHIP_TO_ELIG_RQRD_FLG, customer.CUST_E1_NUM,
           (POSITION('PATIENT NAME' IN UPPER(COALESCE(customer.CUST_NAME, ''))) = 0
            AND ((penny.SHIP_TO_ELIG_RQRD_FLG = 'N' AND customer.CUST_TYPE_CD IN ('B', 'X'))
                 OR (penny.SHIP_TO_ELIG_RQRD_FLG = 'Y' AND customer.CUST_TYPE_CD = 'S'))) AS IS_ON_PENNY_CONTRACT
    FROM IPC ipc
    JOIN PENNY_ACTIVE_ROWS penny ON penny.ITEM_E1_NUM = ipc.ITEM_E1_NUM
    LEFT JOIN CUSTOMER_DETAIL_ROWS customer ON customer.PRCA_NUM = ipc.PRCA_NUM
),
PENNY_ACTIVITY_STATUS AS (
    SELECT PRCA_NUM, ITEM_E1_NUM,
           CASE WHEN COUNT(CUST_E1_NUM) = 0 THEN 'UNKNOWN_CUSTOMER_MAPPING'
                WHEN COUNT_IF(SHIP_TO_ELIG_RQRD_FLG IS NULL) > 0 THEN 'UNKNOWN_CONTRACT_SHIP_TO_FLAG'
                WHEN COUNT_IF(IS_ON_PENNY_CONTRACT) = COUNT(*) THEN 'Y'
                WHEN COUNT_IF(IS_ON_PENNY_CONTRACT) = 0 THEN 'N'
                ELSE 'UNKNOWN_AMBIGUOUS_CUSTOMER_ELIGIBILITY' END AS PENNY_CUSTOMER_STATUS
    FROM PENNY_CUSTOMER_CHECKS
    GROUP BY PRCA_NUM, ITEM_E1_NUM
),
TAP_ROWS AS (
    SELECT DISTINCT ITEM_E1_NUM, GROUPED_LVL2, TIER_1, TIER_2, TIER_3, TIER_4, TIER_5,
                    TIER_6, TIER_7, TIER_8, TIER_9, TIER_10
    FROM PRD_SBX_MMS_DB.VALUEPLUS.MCKB_COST_TAPESTRY
    WHERE ITEM_E1_NUM IN (SELECT ITEM_E1_NUM FROM IPC)
),
TAPESTRY AS (
    SELECT ITEM_E1_NUM, COUNT(*) AS TAPESTRY_MATCHES,
           CASE WHEN COUNT(*) = 1 THEN MIN(GROUPED_LVL2) END AS GROUPED_LVL2,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_1) END AS TIER_1,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_2) END AS TIER_2,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_3) END AS TIER_3,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_4) END AS TIER_4,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_5) END AS TIER_5,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_6) END AS TIER_6,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_7) END AS TIER_7,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_8) END AS TIER_8,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_9) END AS TIER_9,
           CASE WHEN COUNT(*) = 1 THEN MIN(TIER_10) END AS TIER_10
    FROM TAP_ROWS GROUP BY ITEM_E1_NUM
),
ATTACHMENT_ROWS AS (
    SELECT DISTINCT PRCA_NUM, GROUPED_LVL2, ATTACHED_TIER
    FROM PRD_SBX_MMS_DB.PRC.TAP_CUST_ATTACHED_TIERS
    WHERE PRCA_NUM IN (SELECT PRCA_NUM FROM CUSTOMERS)
),
ATTACHMENTS AS (
    SELECT PRCA_NUM, GROUPED_LVL2, COUNT(*) AS ATTACHMENT_MATCHES,
           CASE WHEN COUNT(*) = 1 THEN MIN(TRY_TO_NUMBER(REGEXP_SUBSTR(ATTACHED_TIER, '[0-9]+'))) END AS CURRENT_TIER
    FROM ATTACHMENT_ROWS GROUP BY PRCA_NUM, GROUPED_LVL2
)
SELECT ipc.*, item.ITEM_DSC, item.ITEM_MATCHES, item.PRMRY_UOM, item.REFERENCE_SELL_UOM,
       item.BUY_UOM, item.SELL_TO_BUY_DIVISOR, item.PRMRY_TO_SELL_DIVISOR,
       item.PRMRY_TO_BUY_DIVISOR, item.PRVT_BRND_FLG,
       tapestry.TAPESTRY_MATCHES, tapestry.GROUPED_LVL2,
       tapestry.TIER_1, tapestry.TIER_2, tapestry.TIER_3, tapestry.TIER_4, tapestry.TIER_5,
       tapestry.TIER_6, tapestry.TIER_7, tapestry.TIER_8, tapestry.TIER_9, tapestry.TIER_10,
       IFF(penny.ITEM_E1_NUM IS NULL, 'N', 'Y') AS PENNY_CONTRACT_FLAG,
       penny.PENNY_PRODUCT_TYPES, penny.PENNY_MAN_CONTRACT_IDS,
       penny.PENNY_MCK_CONTRACT_IDS, penny.PENNY_SHIP_TO_ELIG_FLAGS,
       COALESCE(penny.PENNY_CONTRACT_MATCH_COUNT, 0) AS PENNY_CONTRACT_MATCH_COUNT,
       COALESCE(penny.PENNY_CONTRACT_AMBIGUOUS, FALSE) AS PENNY_CONTRACT_AMBIGUOUS,
       COALESCE(penny_status.PENNY_CUSTOMER_STATUS, 'NOT_PENNY_ITEM') AS PENNY_CUSTOMER_STATUS,
       attachment.ATTACHMENT_MATCHES, attachment.CURRENT_TIER
FROM IPC ipc
LEFT JOIN ITEMS item ON item.ITEM_E1_NUM = ipc.ITEM_E1_NUM
LEFT JOIN TAPESTRY tapestry ON tapestry.ITEM_E1_NUM = ipc.ITEM_E1_NUM
LEFT JOIN PENNY_CONTRACTS penny ON penny.ITEM_E1_NUM = ipc.ITEM_E1_NUM
LEFT JOIN PENNY_ACTIVITY_STATUS penny_status ON penny_status.PRCA_NUM = ipc.PRCA_NUM
    AND penny_status.ITEM_E1_NUM = ipc.ITEM_E1_NUM
LEFT JOIN ATTACHMENTS attachment ON attachment.PRCA_NUM = ipc.PRCA_NUM
    AND attachment.GROUPED_LVL2 = tapestry.GROUPED_LVL2
ORDER BY ipc.PRCA_NUM, tapestry.GROUPED_LVL2, ipc.ITEM_E1_NUM, ipc.IPC_SELL_UOM