-- Append-only final decision snapshots for completed Smartsheet requests.
-- Sandbox/test objects only. Apply after the raw intake, validation, and review
-- reference objects have been created. The Python writer enforces idempotency.

CREATE TRANSIENT TABLE IF NOT EXISTS PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_FINAL_DECISIONS_ETL_TEST (
    DECISION_SNAPSHOT_ID VARCHAR(64) NOT NULL,
    DECISION_RECORD_KEY VARCHAR(64) NOT NULL,
    RECORD_HASH VARCHAR(64) NOT NULL,
    REQUEST_ID VARCHAR(255) NOT NULL,
    SOURCE_LINE_KEY VARCHAR(64) NOT NULL,
    SOURCE_INGESTION_RUN_ID VARCHAR(64),
    SOURCE_STAGE VARCHAR(50),
    SOURCE_SHEET_ID VARCHAR(100),
    SOURCE_SHEET_ROW_ID VARCHAR(100),
    SOURCE_ATTACHMENT_ID VARCHAR(100),
    SOURCE_ATTACHMENT_NAME VARCHAR(1000),
    SOURCE_ATTACHMENT_SHA256 VARCHAR(64),
    SOURCE_SHEET_NAME VARCHAR(255),
    SOURCE_ROW_NUMBER NUMBER,
    COMPLETED_FLAG BOOLEAN,
    COMPLETED_DT DATE,
    REJECTED_FLAG BOOLEAN,
    DECISION_STATUS VARCHAR(40) NOT NULL,
    DECISION_REASON VARCHAR(4000),
    SOURCE_ACCOUNT_NUMBER VARCHAR(50),
    RESOLVED_PRCA VARCHAR(50),
    ITEM_E1_NUM VARCHAR(50),
    ITEM_DSC VARCHAR(1000),
    REQUESTED_PRICE_RAW VARCHAR(255),
    REQUESTED_PRICE NUMBER(38,10),
    REQUESTED_UOM VARCHAR(30),
    SELL_UOM_PRICE NUMBER(38,10),
    SELL_UOM VARCHAR(30),
    BUY_UOM VARCHAR(30),
    PRMRY_UOM VARCHAR(30),
    SELL_TO_BUY_DIVISOR NUMBER(38,10),
    PRMRY_TO_SELL_DIVISOR NUMBER(38,10),
    PRMRY_TO_BUY_DIVISOR NUMBER(38,10),
    ASSIGNED_TIER NUMBER(2,0),
    TAPESTRY_COST_SELL_UOM NUMBER(38,10),
    PENNY_CONTRACT_FLAG VARCHAR(10),
    PENNY_CONTRACT_REQUIRED_FLAG VARCHAR(10),
    PENNY_PRICE_TEST_STATUS VARCHAR(100),
    PENNY_PRODUCT_TYPES VARCHAR(1000),
    PENNY_MAN_CONTRACT_IDS VARCHAR(2000),
    PENNY_MCK_CONTRACT_IDS VARCHAR(2000),
    PENNY_CONTRACT_AMBIGUOUS BOOLEAN,
    PENNY_CUSTOMER_STATUS VARCHAR(100),
    SOURCE_HASH VARCHAR(64) NOT NULL,
    REFERENCE_HASH VARCHAR(64) NOT NULL,
    SNAPSHOT_AT TIMESTAMP_NTZ NOT NULL
);

CREATE OR REPLACE VIEW PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_FINAL_DECISIONS_FOR_PBI_ETL_TEST AS
SELECT * EXCLUDE (LATEST_ROW_NUM)
FROM (
    SELECT decision.*,
           ROW_NUMBER() OVER (
               PARTITION BY REQUEST_ID, SOURCE_LINE_KEY
               ORDER BY SNAPSHOT_AT DESC, DECISION_SNAPSHOT_ID DESC
           ) AS LATEST_ROW_NUM
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_FINAL_DECISIONS_ETL_TEST decision
)
WHERE LATEST_ROW_NUM = 1;

CREATE OR REPLACE VIEW PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_WORKFLOW_STATUS_FOR_PBI_ETL_TEST AS
WITH latest_header AS (
    SELECT raw_header.*, status.RESOLVED_PRCA
    FROM (
        SELECT *
        FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_HEADER_ETL_TEST
        QUALIFY ROW_NUMBER() OVER (
            PARTITION BY ROW_ID
            ORDER BY EXTRACTED_AT DESC, INGESTION_RUN_ID DESC
        ) = 1
    ) raw_header
    LEFT JOIN PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_STATUS_ETL_TEST status
        ON status.REQUEST_ID = raw_header.ROW_ID
       AND status.INGESTION_RUN_ID = raw_header.INGESTION_RUN_ID
),
line_counts AS (
    SELECT line.ROW_ID, line.INGESTION_RUN_ID, COUNT(*) AS SOURCE_LINE_COUNT
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_LINES_ETL_TEST line
    INNER JOIN latest_header header
        ON header.ROW_ID = line.ROW_ID
       AND header.INGESTION_RUN_ID = line.INGESTION_RUN_ID
    GROUP BY line.ROW_ID, line.INGESTION_RUN_ID
),
latest_decisions AS (
    SELECT decision.*
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_FINAL_DECISIONS_FOR_PBI_ETL_TEST decision
    INNER JOIN latest_header header
        ON header.ROW_ID = decision.REQUEST_ID
       AND header.INGESTION_RUN_ID = decision.SOURCE_INGESTION_RUN_ID
),
decision_counts AS (
    SELECT REQUEST_ID, SOURCE_INGESTION_RUN_ID,
           COUNT(*) AS SNAPSHOTTED_LINE_COUNT,
           COUNT_IF(DECISION_STATUS = 'APPROVED') AS APPROVED_LINE_COUNT,
           COUNT_IF(DECISION_STATUS = 'REJECTED') AS REJECTED_LINE_COUNT,
           COUNT_IF(DECISION_STATUS = 'NOT_EVALUATED') AS NOT_EVALUATED_LINE_COUNT,
           MAX(SNAPSHOT_AT) AS FINAL_SNAPSHOT_AT
    FROM latest_decisions
    GROUP BY REQUEST_ID, SOURCE_INGESTION_RUN_ID
)
SELECT header.ROW_ID AS REQUEST_ID,
       header.CUST_NUM_PRCA AS SOURCE_PRCA,
       header.RESOLVED_PRCA,
       header.SOURCE_STAGE,
       header.SOURCE_SHEET_ID,
       header.SOURCE_SHEET_ROW_ID,
       header.CREATED_DT,
       TRY_TO_BOOLEAN(header.CMPLTD_FLG) AS COMPLETED_FLAG,
       header.CMPLTD_DT AS COMPLETED_DT,
       header.INGESTION_RUN_ID,
       header.EXTRACTED_AT,
       COALESCE(lines.SOURCE_LINE_COUNT, 0) AS SOURCE_LINE_COUNT,
       COALESCE(decisions.SNAPSHOTTED_LINE_COUNT, 0) AS SNAPSHOTTED_LINE_COUNT,
       COALESCE(decisions.APPROVED_LINE_COUNT, 0) AS APPROVED_LINE_COUNT,
       COALESCE(decisions.REJECTED_LINE_COUNT, 0) AS REJECTED_LINE_COUNT,
       COALESCE(decisions.NOT_EVALUATED_LINE_COUNT, 0) AS NOT_EVALUATED_LINE_COUNT,
       decisions.FINAL_SNAPSHOT_AT,
       CASE
           WHEN LOWER(COALESCE(header.SOURCE_STAGE, '')) = 'rejected'
             OR COALESCE(TRY_TO_BOOLEAN(TRY_PARSE_JSON(header.SOURCE_HEADER_JSON):Rejected::VARCHAR), FALSE)
               THEN 'REJECTED'
           WHEN NOT COALESCE(TRY_TO_BOOLEAN(header.CMPLTD_FLG), FALSE)
               THEN 'PENDING_ANALYST_REVIEW'
           WHEN COALESCE(lines.SOURCE_LINE_COUNT, 0) = 0
               THEN 'COMPLETED_NO_LINE_ITEMS'
           WHEN COALESCE(decisions.SNAPSHOTTED_LINE_COUNT, 0) = 0
               THEN 'COMPLETED_AWAITING_FINAL_SNAPSHOT'
           WHEN decisions.REJECTED_LINE_COUNT = decisions.SNAPSHOTTED_LINE_COUNT
               THEN 'REJECTED'
           WHEN decisions.NOT_EVALUATED_LINE_COUNT > 0
               THEN 'COMPLETED_WITH_UNEVALUATED_LINES'
           WHEN decisions.APPROVED_LINE_COUNT = lines.SOURCE_LINE_COUNT
               THEN 'APPROVED'
           ELSE 'COMPLETED_PARTIALLY_DECIDED'
       END AS REQUEST_STATUS
FROM latest_header header
LEFT JOIN line_counts lines
    ON lines.ROW_ID = header.ROW_ID
   AND lines.INGESTION_RUN_ID = header.INGESTION_RUN_ID
LEFT JOIN decision_counts decisions
    ON decisions.REQUEST_ID = header.ROW_ID
   AND decisions.SOURCE_INGESTION_RUN_ID = header.INGESTION_RUN_ID;