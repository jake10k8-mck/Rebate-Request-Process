-- Read models over append-only raw Smartsheet ETL tables.
-- No raw table rows are updated by these views.

CREATE OR REPLACE VIEW PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_STATUS_ETL_TEST AS
WITH latest_header AS (
    SELECT *
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_HEADER_ETL_TEST
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ROW_ID
        ORDER BY EXTRACTED_AT DESC, INGESTION_RUN_ID DESC
    ) = 1
),
latest_header_validation AS (
    SELECT *
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_VALIDATION_AUDIT_ETL_TEST
    WHERE RECORD_TYPE = 'HEADER'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY REQUEST_ID, INGESTION_RUN_ID
        ORDER BY VALIDATED_AT DESC, VALIDATION_RUN_ID DESC
    ) = 1
),
latest_attachments AS (
    SELECT attachment.*
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_ATTACHMENTS_ETL_TEST attachment
    INNER JOIN latest_header header
        ON header.ROW_ID = attachment.ROW_ID
       AND header.INGESTION_RUN_ID = attachment.INGESTION_RUN_ID
),
attachment_summary AS (
    SELECT
        ROW_ID,
        COUNT(*) AS ATTACHMENT_COUNT,
        COUNT_IF(LOWER(FILE_EXTENSION) IN ('.xlsx', '.csv')) AS SUPPORTED_ATTACHMENT_COUNT,
        COUNT_IF(DOWNLOAD_STATUS = 'FAILED') AS DOWNLOAD_FAILURE_COUNT,
        COUNT_IF(PARSE_STATUS = 'FAILED') AS PARSE_FAILURE_COUNT,
        COUNT_IF(PARSE_STATUS = 'UNSUPPORTED') AS UNSUPPORTED_COUNT,
        LISTAGG(ERROR_REASON, ' | ') WITHIN GROUP (ORDER BY ATTACHMENT_NAME) AS ATTACHMENT_ERROR_DETAILS
    FROM latest_attachments
    GROUP BY ROW_ID
),
latest_lines AS (
    SELECT line.*
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_LINES_ETL_TEST line
    INNER JOIN latest_header header
        ON header.ROW_ID = line.ROW_ID
       AND header.INGESTION_RUN_ID = line.INGESTION_RUN_ID
),
line_summary AS (
    SELECT ROW_ID, COUNT(*) AS EXTRACTED_LINE_COUNT
    FROM latest_lines
    GROUP BY ROW_ID
),
status_facts AS (
    SELECT
        header.*,
        COALESCE(attachment.ATTACHMENT_COUNT, 0) AS ATTACHMENT_RECORD_COUNT,
        COALESCE(attachment.SUPPORTED_ATTACHMENT_COUNT, 0) AS SUPPORTED_ATTACHMENT_COUNT,
        COALESCE(attachment.DOWNLOAD_FAILURE_COUNT, 0) AS DOWNLOAD_FAILURE_COUNT,
        COALESCE(attachment.PARSE_FAILURE_COUNT, 0) AS PARSE_FAILURE_COUNT,
        COALESCE(attachment.UNSUPPORTED_COUNT, 0) AS UNSUPPORTED_COUNT,
        attachment.ATTACHMENT_ERROR_DETAILS,
        COALESCE(line.EXTRACTED_LINE_COUNT, 0) AS EXTRACTED_LINE_COUNT,
        validation.E1_ACCOUNT_STATUS AS PRCA_STATUS,
        validation.PEX_STATUS,
        validation.RESOLVED_PRCA,
        validation.VALIDATION_RUN_ID,
        validation.HEADER_INTAKE_STATUS AS VALIDATED_INTAKE_STATUS,
        validation.FAILURE_REASON AS VALIDATION_FAILURE_REASON
    FROM latest_header header
    LEFT JOIN attachment_summary attachment ON attachment.ROW_ID = header.ROW_ID
    LEFT JOIN line_summary line ON line.ROW_ID = header.ROW_ID
    LEFT JOIN latest_header_validation validation
        ON validation.REQUEST_ID = header.ROW_ID
       AND validation.INGESTION_RUN_ID = header.INGESTION_RUN_ID
)
SELECT
    ROW_ID AS REQUEST_ID,
    CREATED_DT,
    CUST_NUM_PRCA AS SOURCE_PRCA,
    BUS_PLTFRM_DSC AS SOURCE_SALES_SEGMENT,
    SOURCE_STAGE,
    SOURCE_SHEET_ID,
    SOURCE_SHEET_ROW_ID,
    REQUESTER_NAME,
    ADDITIONAL_NOTES,
    ATTACHMENT_COUNT AS SOURCE_ATTACHMENT_COUNT,
    INGESTION_RUN_ID,
    EXTRACTED_AT,
    COALESCE(PRCA_STATUS, 'NOT_VALIDATED') AS E1_ACCOUNT_STATUS,
    COALESCE(PEX_STATUS, 'NOT_VALIDATED') AS PEX_STATUS,
    RESOLVED_PRCA,
    VALIDATION_RUN_ID,
    ATTACHMENT_RECORD_COUNT AS ATTACHMENT_COUNT,
    SUPPORTED_ATTACHMENT_COUNT,
    EXTRACTED_LINE_COUNT,
    ATTACHMENT_ERROR_DETAILS,
    CASE
        WHEN ATTACHMENT_RECORD_COUNT = 0 THEN 'MISSING'
        WHEN UNSUPPORTED_COUNT > 0 AND SUPPORTED_ATTACHMENT_COUNT = 0 THEN 'UNSUPPORTED'
        WHEN DOWNLOAD_FAILURE_COUNT > 0 THEN 'DOWNLOAD_FAILED'
        WHEN PARSE_FAILURE_COUNT > 0 THEN 'PARSE_FAILED'
        WHEN EXTRACTED_LINE_COUNT = 0 THEN 'PRESENT_NO_LINES_EXTRACTED'
        ELSE 'LINES_EXTRACTED'
    END AS ATTACHMENT_STATUS,
    COALESCE(VALIDATED_INTAKE_STATUS, 'NOT_VALIDATED') AS INTAKE_STATUS,
    COALESCE(VALIDATION_FAILURE_REASON, ATTACHMENT_ERROR_DETAILS) AS FAILURE_REASON
FROM status_facts;

CREATE OR REPLACE VIEW PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_LINES_FOR_PBI_ETL_TEST AS
WITH latest_header AS (
    SELECT ROW_ID, INGESTION_RUN_ID
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_HEADER_ETL_TEST
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ROW_ID
        ORDER BY EXTRACTED_AT DESC, INGESTION_RUN_ID DESC
    ) = 1
),
latest_line_validation AS (
    SELECT *
    FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_VALIDATION_AUDIT_ETL_TEST
    WHERE RECORD_TYPE = 'LINE'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY REQUEST_ID, INGESTION_RUN_ID, SOURCE_LINE_KEY
        ORDER BY VALIDATED_AT DESC, VALIDATION_RUN_ID DESC
    ) = 1
)
SELECT
    header_status.INTAKE_STATUS,
    header_status.FAILURE_REASON AS HEADER_FAILURE_REASON,
    validation.VALIDATION_RUN_ID,
    line.ROW_ID AS REQUEST_ID,
    line.INGESTION_RUN_ID,
    line.SOURCE_ATTACHMENT_ID,
    line.SOURCE_ATTACHMENT_NAME,
    line.SOURCE_ATTACHMENT_SHA256,
    line.SOURCE_SHEET_NAME,
    line.SOURCE_ROW_NUMBER,
    line.ITEM_E1_NUM,
    line.ITEM_DSC,
    line.REQ_UOM,
    line.REQ_PRICE_RAW,
    line.REQ_PRICE,
    validation.E1_ACCOUNT_STATUS,
    validation.RESOLVED_PRCA,
    validation.PEX_STATUS,
    validation.ITEM_STATUS,
    validation.REFERENCE_SELL_UOM,
    validation.EFFECTIVE_UOM,
    validation.UOM_ASSUMED,
    validation.UOM_STATUS,
    validation.TIER_10_COST,
    validation.PRICE_FLOOR_STATUS,
    validation.LINE_VALIDATION_STATUS,
    validation.FAILURE_REASON AS LINE_FAILURE_REASON
FROM PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_LINES_ETL_TEST line
INNER JOIN latest_header latest
    ON latest.ROW_ID = line.ROW_ID
   AND latest.INGESTION_RUN_ID = line.INGESTION_RUN_ID
INNER JOIN PRD_SBX_MMS_DB.PRC.EC_REBATE_REQUEST_STATUS_ETL_TEST header_status
    ON header_status.REQUEST_ID = line.ROW_ID
   AND header_status.INGESTION_RUN_ID = line.INGESTION_RUN_ID
INNER JOIN latest_line_validation validation
    ON validation.REQUEST_ID = line.ROW_ID
   AND validation.INGESTION_RUN_ID = line.INGESTION_RUN_ID
   AND validation.SOURCE_LINE_KEY = SHA2_HEX(CONCAT_WS('|', line.ROW_ID,
       line.INGESTION_RUN_ID, line.SOURCE_ATTACHMENT_ID, line.SOURCE_SHEET_NAME,
       TO_VARCHAR(line.SOURCE_ROW_NUMBER)), 256)
WHERE header_status.INTAKE_STATUS = 'READY_FOR_LINE_VALIDATION';
