PORTFOLIO_MARGIN AS (
SELECT 
    WE.PRCA_NUM,
    --TAPAT.PRCA_NUM,
    WE.GROUPED_LVL2,
    WE.LAC_TIER,
   --/PROD_CTGRY_LVL2_CD,PROD_CTGRY_LVL2_DSC,
    --TAPAT.GROUPED_LVL2,
   -- TAPAT.TIER,
    ROUND(SUM(ITEM_WEIGHT * MARGIN_LDD), 3) AS PORTFOLIO_MARGIN,
    --ROUND(SUM(PROSPECTIVE_ITEM_WEIGHT * PROSPECTIVE_MARGIN), 3) AS PROPSECTIVE_PORTFOLIO_MARGIN,
    
    ROUND(SUM(SLS), 2) AS TOTAL_SALES,
    ROUND(SUM(BUYSIDE_LOSS),2) AS CUMULATIVE_BUYSIDE_LOSS
    --ROUND(SUM(PROPOSED_SLS), 2) AS TOTAL_PROSPECTIVE_SALES
FROM (
    SELECT 
        PRCA_NUM,
        GROUPED_LVL2,
        --PROD_CTGRY_LVL2_CD,PROD_CTGRY_LVL2_DSC,
        ITEM_E1_NUM,
        LAC_TIER,
        SLS,
        BUYSIDE_LOSS,
        PROPOSED_SLS,
        MARGIN_LDD,
        PROSPECTIVE_MARGIN,
        SLS / SUM(SLS) OVER (PARTITION BY PRCA_NUM, GROUPED_LVL2 --,PROD_CTGRY_LVL2_CD
        ) AS ITEM_WEIGHT
       -- PROPOSED_SLS / SUM(PROPOSED_SLS) OVER (PARTITION BY PRCA_NUM,GROUPED_LVL2) AS PROSPECTIVE_ITEM_WEIGHT
    FROM ITEM_DETAIL
    --WHERE SLS IS NOT NULL AND MARGIN_LDD IS NOT NULL
) WE
--LEFT JOIN TAPESTRY_ATTACHED_TIER TAPAT ON TAPAT.GROUPED_LVL2 = WE.GROUPED_LVL2 AND TAPAT.PRCA_NUM = WE.GROUPED_LVL2
GROUP BY ALL
ORDER BY TOTAL_SALES DESC
),

NEGATIVE_MARGIN_COUNT AS (
SELECT 
    PRCA_NUM,
    GROUPED_LVL2,
    --PROD_CTGRY_LVL2_CD,PROD_CTGRY_LVL2_DSC,
    COUNT_IF(SORT = 1) AS ITEMS_WITH_ACTIVITY,
    COUNT_IF(MARGIN_LDD < 0) AS ITEMS_NEGATIVE_MARGIN,
    COUNT_IF(PROSPECTIVE_MARGIN < 0) AS PROSPECTIVE_NEG_MARGIN
FROM ITEM_DETAIL
GROUP BY ALL
ORDER BY GROUPED_LVL2
),

PRCA_MARGIN AS (
    SELECT 
        PRCA_NUM,
        ROUND(SUM(GRP_WEIGHT * PORTFOLIO_MARGIN), 4) AS WEIGHTED_PRCA_MARGIN,
        ROUND(SUM(TOTAL_SALES), 2) AS PRCA_TOTAL_SALES
    FROM (
        SELECT 
            PRCA_NUM,
            GROUPED_LVL2,
          --  PROD_CTGRY_LVL2_CD,--
            PORTFOLIO_MARGIN,
            TOTAL_SALES,
            TOTAL_SALES / SUM(TOTAL_SALES) OVER (PARTITION BY PRCA_NUM) AS GRP_WEIGHT
        FROM PORTFOLIO_MARGIN
        WHERE TOTAL_SALES IS NOT NULL AND PORTFOLIO_MARGIN IS NOT NULL
    )
    GROUP BY PRCA_NUM
    ORDER BY PRCA_TOTAL_SALES DESC
)

