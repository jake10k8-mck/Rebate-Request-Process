  --IPC.PRICE_SOURCE,
  IPC.BID_OR_PRCA,
  ipc.item_e1_num ,
  IPC.UNIT_PRICE,
  SUM(IPC.QTY_3_MTH) AS ITM_QTY,
  SUM(ipc.SLS_3_MTH) AS ITM_SUM
FROM PRD_SBX_MMS_DB.MRGN.HAH_IPC IPC
WHERE IPC.BID_OR_PRCA IN (SELECT DISTINCT PRCA_NUM FROM CUSTOMERS)
--AND ipc.item_e1_num IN (SELECT ITEM_E1_NUM FROM ITEMS)
