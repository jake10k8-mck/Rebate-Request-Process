ITEM_DETAIL AS (    
SELECT  DM.HCN_CUST_SIZE ,
CUST.PRCA_NUM, TAPAT.GROUPED_LVL2, ITM.PROD_CTGRY_LVL2_CD, ITM.PROD_CTGRY_LVL2_DSC ,TU.TIER_NUM, TU_2.TIER_NUM AS NEW_ITEM_TIER, ITM.ITEM_E1_NUM, ITM.ITEM_DSC,ITM.SELL_UOM,IDT.INPUT_SELL_PRICE,  
round(IP.UNIT_PRICE,2) AS PRICE ,
CASE WHEN INPUT_SELL_PRICE IS NOT NULL
THEN INPUT_SELL_PRICE ELSE PRICE END AS PROSPECTIVE_PRICE,

TU.TIER_COST,TU_2.TIER_COST AS NEW_ITEM_COST,
--GPL.CLY55MCKNC AS GPO_LD, 
ROUND((IP.UNIT_PRICE - TU.TIER_COST)/IP.UNIT_PRICE,2) AS MARGIN_LDD ,

  CASE WHEN IDT.INPUT_SELL_PRICE IS NOT NULL
 THEN ROUND((IDT.INPUT_SELL_PRICE - TU.TIER_COST)/IDT.INPUT_SELL_PRICE,2)
 ELSE NULL END AS NEW_PRICE_MARGIN,
 
CASE WHEN PROSPECTIVE_PRICE IS NOT NULL
THEN ROUND((PROSPECTIVE_PRICE-TU.TIER_COST)/PROSPECTIVE_PRICE,2) ELSE NULL END AS PROSPECTIVE_MARGIN,

ROUND(IP.ITM_SUM,2) AS SLS, 

TU_3.TIER_COST,
IPT.TIER AS LAC_TIER,

ROUND((TU_3.TIER_COST - TU.TIER_COST)*ITM_QTY,2) AS BUYSIDE_LOSS,

TAPAT.REASON,ITM_SUM,ITM_QTY, IDT.INPUT_USAGE, PROSPECTIVE_PRICE*ITM_QTY AS PROSPECTIVE_SLS, IDT.INPUT_USAGE*PROSPECTIVE_PRICE AS PROPOSED_SLS,
CASE WHEN IP.ITM_SUM IS NOT NULL OR IDT.INPUT_SELL_PRICE IS NOT NULL THEN 1 ELSE 0 END AS SORT,
CASE WHEN UPDATE_DATE = CURRENT_DATE() THEN 'CHANGE' ELSE 'NO CHANGE' END AS COST_STATUS

FROM CUSTOMERS CUST
LEFT JOIN TAPESTRY_ATTACHED_TIER TAPAT ON CUST.PRCA_NUM = TAPAT.PRCA_NUM
INNER JOIN TAPESTRY_UNPIVOT TU ON TU.GROUPED_LVL2 = TAPAT.GROUPED_LVL2 AND TU.TIER_NUM = CAST(REGEXP_SUBSTR(TAPAT.ATTACHED_TIER, '\\d+') AS INTEGER)
INNER JOIN ITEMS ITM ON ITM.ITEM_E1_NUM = TU.ITEM_E1_NUM
LEFT JOIN IPC IP ON IP.BID_OR_PRCA = CUST.PRCA_NUM AND IP.ITEM_E1_NUM = TU.ITEM_E1_NUM
LEFT JOIN INPUT_DT IDT ON IDT.PRCA_NUM = CUST.PRCA_NUM AND IDT.INPUT_ITEM_E1_NUM = ITM.ITEM_E1_NUM
LEFT JOIN TAPESTRY_UNPIVOT TU_2 ON TU_2.ITEM_E1_NUM = ITM.ITEM_E1_NUM
LEFT JOIN DECISION_MAKER DM ON CUST.PRCA_NUM = DM.PRCA_NUM
LEFT JOIN INPUT_TIER IPT ON IPT.GROUPED_LVL2 = TAPAT.GROUPED_LVL2 --AND IPT.TIER = TAPAT.TIER
LEFT JOIN TAPESTRY_UNPIVOT TU_3 ON TU_3.ITEM_E1_NUM = ITM.ITEM_E1_NUM AND TU_3.TIER_NUM = IPT.TIER
QUALIFY
    ROW_NUMBER() OVER (
        PARTITION BY CUST.PRCA_NUM, ITM.ITEM_E1_NUM
        ORDER BY 
        CASE WHEN IDT.INPUT_SELL_PRICE IS NOT NULL
        THEN ABS (TU_2.benchmark_price - IDT.INPUT_SELL_PRICE)
        ELSE ABS (TU.TIER_NUM - TU_2.TIER_NUM) END ASC
    ) = 1
--LEFT JOIN GPO_LOADS GPL ON GPL.PRCA_NUM = CUST.PRCA_NUM
ORDER BY SORT DESC, TAPAT.GROUPED_LVL2, IP.ITM_SUM DESC, ITM.ITEM_E1_NUM
