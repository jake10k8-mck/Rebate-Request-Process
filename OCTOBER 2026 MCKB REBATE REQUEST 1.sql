  (AC_ACQ_COST - i.MAC_COST_AMT)/AC_ACQ_COST AS BUY_MARGIN
  FROM PRD_PL_MMS_EDW_DB.EDWRPT.V_DIM_ITEM_E1_CURR i
  WHERE i.PRVT_BRND_FLG = 'Y'
  AND i.STOCK_TYPE_CD != 'O'
),

