),

TAPESTRY_UNPIVOT AS (
  SELECT T_3.*, ROUND(T_3.TIER_COST/(1-CASE T_3.TIER_NUM
      WHEN 1 THEN 0.25 WHEN 2 THEN 0.23 WHEN 3 THEN 0.21 WHEN 4 THEN 0.18 WHEN 5 THEN 0.16
      WHEN 6 THEN 0.14 WHEN 7 THEN 0.12 WHEN 8 THEN 0.09 WHEN 9 THEN 0.07 WHEN 10 THEN 0.05
  END),2) AS BENCHMARK_PRICE
  FROM
  (SELECT
      TAP.ITEM_E1_NUM,
      TAP.GROUPED_LVL2,
      REGEXP_SUBSTR(TIER_NAME, '[0-9]+')::NUMBER AS TIER_NUM,
      TIER_COST
    FROM PRD_SBX_MMS_DB.VALUEPLUS.MCKB_COST_TAPESTRY TAP


    UNPIVOT (
        TIER_COST FOR TIER_NAME IN (
          Tier_1,
          Tier_2,
          Tier_3,
          Tier_4,
          Tier_5,
          Tier_6,
          Tier_7,
          Tier_8,
          Tier_9,
          Tier_10
        )
    )) T_3

