CUSTOMERS AS (
  SELECT DISTINCT Cust.PRCA_NUM, Cust.CUST_E1_NUM, MMS_SUB_CLASS_CD
  FROM PRD_PL_MMS_EDW_DB.EDWRPT.V_DIM_CUST_CURR Cust
  WHERE Cust.SYS_PLTFRM = 'E1'
  AND Cust.CUST_TYPE_CD IN ('B','S','X')
  AND CUST.CUST_E1_NUM IN 
